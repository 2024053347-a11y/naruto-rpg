#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const canonRoot = path.join(root, 'canon-rebuild-output', 'data', 'canon');
const outputDir = path.join(root, 'js', 'data', 'generated');
const outputFile = path.join(outputDir, 'canon-runtime-data.js');

const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
const readManifestRecords = (subdir) => {
  const base = path.join(canonRoot, subdir);
  const manifest = readJson(path.join(base, 'manifest.json'));
  return {
    manifest,
    shards: manifest.shards.map(shard => ({
      ...shard,
      records: readJson(path.join(base, shard.path)).records || []
    }))
  };
};

const projectTimelineRoot = path.join(canonRoot, 'project-timeline');
const projectTimelineManifest = readJson(path.join(projectTimelineRoot, 'manifest.json'));
const projectTimelineShards = projectTimelineManifest.shards.map(shard => ({
  ...shard,
  days: readJson(path.join(projectTimelineRoot, shard.path)).days || []
}));
const techniqueSource = readManifestRecords('techniques');

const plotDays = projectTimelineShards
  .flatMap(shard => shard.days)
  .sort((a, b) => a.date.localeCompare(b.date) || a.id.localeCompare(b.id));
const plotScenes = plotDays.flatMap(day => day.scenes.map((scene, order) => ({
  ...scene,
  day_id: day.id,
  date: day.date,
  arc_id: day.arc_id,
  order: order + 1
})));
const plotBeats = plotScenes.flatMap(scene => scene.beats.map(beat => ({
  ...beat,
  day_id: scene.day_id,
  scene_id: scene.id,
  date: scene.date,
  arc_id: scene.arc_id,
  thread_id: scene.thread_id
})));
const timelineYearSnapshots = plotDays.filter(day => day.year_snapshot && typeof day.year_snapshot === 'object').length;

const plotIds = new Set([...plotDays, ...plotScenes, ...plotBeats].map(record => record.id));
if (plotIds.size !== plotDays.length + plotScenes.length + plotBeats.length) {
  throw new Error('project.timeline.v2 contains duplicate DAY/SCN/EV IDs');
}
if ([...plotIds].some(id => /^EV-NAR-/.test(id))) {
  throw new Error('project.timeline.v2 runtime must not contain legacy EV-NAR IDs');
}

const resourceFor = record => record.resource_type
  || (record.state_type === 'genjutsu' ? 'spirit' : record.state_type === 'taijutsu' ? 'stamina' : 'chakra');

const techniques = techniqueSource.shards
  .flatMap(shard => shard.records)
  .map(record => ({
    id: record.id,
    name: record.canonical_name || '',
    aliases: record.aliases || [],
    lookup_aliases: record.lookup_aliases || [],
    type: record.state_type || 'jutsu',
    classes: record.classes || [],
    lookup_classes: record.lookup_classes || [],
    rank: record.rank || '特',
    elements: record.elements || [],
    lookup_elements: record.lookup_elements || [],
    resource: resourceFor(record),
    cost: Math.max(0, Number(record.cost) || 0),
    costDesign: record.cost_design || null,
    power: Math.max(0, Number(record.power) || 0),
    powerMode: record.power_mode || 'none',
    summary: record.effect?.summary || '',
    limitations: record.limitations || [],
    access: record.access || {},
    users: (record.known_users || []).map(user => user.character_id).filter(Boolean),
    availability: record.availability || {},
    review: record.qa?.status || 'draft'
  }))
  .sort((a, b) => a.id.localeCompare(b.id));

const hash = value => crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');
const meta = {
  timelineSchemaVersion: projectTimelineManifest.schema_version,
  timelineScope: projectTimelineManifest.scope || '',
  timelineSupportedNamespaces: projectTimelineManifest.supported_namespaces || [],
  timelineIncludedNamespaces: projectTimelineManifest.included_namespaces || [],
  timelineCoverage: projectTimelineManifest.coverage || null,
  timelineDays: plotDays.length,
  timelineYearSnapshots,
  timelineScenes: plotScenes.length,
  timelineBeats: plotBeats.length,
  techniqueRecords: techniques.length,
  timelineAuthority: projectTimelineManifest.authority,
  timelineDateVersion: projectTimelineManifest.date_version || '',
  techniqueBalanceVersion: techniqueSource.manifest.balance_version || '',
  timelineHash: hash(plotDays),
  techniqueHash: hash(techniques)
};

fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(outputFile, [
  '// Generated by scripts/build-canon-runtime.mjs. Do not edit by hand.',
  `export const CANON_RUNTIME_META = ${JSON.stringify(meta)};`,
  `export const CANON_PLOT_DAYS = ${JSON.stringify(plotDays)};`,
  `export const CANON_PLOT_SCENES = ${JSON.stringify(plotScenes)};`,
  `export const CANON_PLOT_BEATS = ${JSON.stringify(plotBeats)};`,
  `export const CANON_TECHNIQUES = ${JSON.stringify(techniques)};`,
  ''
].join('\n'));

console.log(`Built canon runtime: ${plotDays.length} plot days (${timelineYearSnapshots} year snapshots), ${plotScenes.length} scenes, ${plotBeats.length} beats, ${techniques.length} techniques`);
